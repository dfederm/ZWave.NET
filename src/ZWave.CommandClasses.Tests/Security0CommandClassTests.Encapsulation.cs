    [TestMethod]
    public void Encapsulation_SenderNonce_NotTrackedInOwnPool()
    {
        (S0SecurityManager sender, S0SecurityManager receiver) = CreateManagers();

        byte[] receiverNonce = receiver.GenerateNonce(receiver: 1);
        sender.StoreReceivedNonce(issuer: 2, receiverNonce);

        CommandClassFrame inner = CommandClassFrame.Create(CommandClassId.BinarySwitch, 0x01, [0x01]);
        Security0CommandClass.CommandEncapsulationCommand command =
            Security0CommandClass.CommandEncapsulationCommand.Create(sender, srcNodeId: 1, dstNodeId: 2, inner, 0x00);

        // The sender nonce is the first 8 bytes of the command parameters. It must not be
        // retrievable from the sender's own pool: it was generated for this frame, not issued
        // to a peer, so Parse must never accept an inbound command that references it.
        byte[] senderNonce = command.Frame.CommandParameters.Span[..8].ToArray();
        ReadOnlySpan<byte> ownNonce = sender.GetOwnNonce(senderNonce[0], sourceNodeId: 2);

        Assert.IsTrue(ownNonce.IsEmpty);
    }

    [TestMethod]
    public void Encapsulation_NonceIssuedToOtherPeer_RejectsFrameFromDifferentNode()
    {
        // Node 1 issues a nonce to peer 2. A different node (3) that has learned the nonce value
        // (e.g. by eavesdropping the Nonce Report) must not be able to consume node 1's nonce
        // slot, even though it can compute a valid MAC (all S0 nodes share the network key).
        S0SecurityManager receiver = new(ownNodeId: 1);
        receiver.SetNetworkKey(NetworkKey);
        byte[] issuedNonce = receiver.GenerateNonce(receiver: 2);

        S0SecurityManager attacker = new(ownNodeId: 3);
        attacker.SetNetworkKey(NetworkKey);
        attacker.StoreReceivedNonce(issuer: 1, issuedNonce);

        CommandClassFrame inner = CommandClassFrame.Create(CommandClassId.BinarySwitch, 0x01, [0x01]);
        Security0CommandClass.CommandEncapsulationCommand command =
            Security0CommandClass.CommandEncapsulationCommand.Create(attacker, srcNodeId: 3, dstNodeId: 1, inner, 0x00);

        Security0Encapsulation? result =
            Security0CommandClass.CommandEncapsulationCommand.Parse(receiver, srcNodeId: 3, dstNodeId: 1, command.Frame, NullLogger.Instance);

        Assert.IsNull(result);
    }

    [TestMethod]
    public void ConsumeOwnNonce_ConcurrentCalls_OnlyOneConsumes()
    {
        // A nonce is single-use, so of many concurrent attempts to consume the same nonce ID,
        // exactly one must succeed. This is the invariant the atomic lookup-and-remove in
        // ConsumeOwnNonce enforces (a split check-then-delete would let two callers through).
        S0SecurityManager manager = new(ownNodeId: 1);
        byte[] nonce = manager.GenerateNonce(receiver: 2);
        byte nonceId = nonce[0];

        const int Callers = 32;
        Task<byte[]?>[] tasks = new Task<byte[]?>[Callers];
        for (int i = 0; i < Callers; i++)
        {
            tasks[i] = Task.Run(() => manager.ConsumeOwnNonce(nonceId, sourceNodeId: 2));
        }

        Task.WaitAll(tasks);

        int consumed = 0;
        foreach (Task<byte[]?> task in tasks)
        {
            if (task.Result is not null)
            {
                consumed++;
            }
        }

        Assert.AreEqual(1, consumed);
    }
