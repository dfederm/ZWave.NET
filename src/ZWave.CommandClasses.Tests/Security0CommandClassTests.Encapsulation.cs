    [TestMethod]
    public void Encapsulation_TwoPartyARoundTripsB()
    {
        (S0SecurityManager sender, S0SecurityManager receiver) = CreateManagers();

        // The receiver generates its nonce; the sender stores it as if received via a Nonce Report.
        byte[] receiverNonce = receiver.GenerateNonce(receiver: 1);
        sender.StoreReceivedNonce(issuer: 2, receiverNonce);

        CommandClassFrame inner = CommandClassFrame.Create(CommandClassId.BinarySwitch, 0x01, [0x01]);
        Security0CommandClass.CommandEncapsulationCommand command =
            Security0CommandClass.CommandEncapsulationCommand.Create(sender, srcNodeId: 1, dstNodeId: 2, inner, 0x00);

        Security0Encapsulation? result =
            Security0CommandClass.CommandEncapsulationCommand.Parse(receiver, srcNodeId: 1, dstNodeId: 2, command.Frame, NullLogger.Instance);

        Assert.IsNotNull(result);
        Assert.AreEqual((byte)0x00, result.Value.FrameControl);
        Assert.AreEqual(Hex(inner.Data.Span.ToArray()), Hex(result.Value.EncapsulatedFrame.Data.Span.ToArray()));
    }

    [TestMethod]
    public void Encapsulation_CiphertextDiffersFromPlaintext()
    {
        (S0SecurityManager sender, S0SecurityManager receiver) = CreateManagers();

        byte[] receiverNonce = receiver.GenerateNonce(receiver: 1);
        sender.StoreReceivedNonce(issuer: 2, receiverNonce);

        CommandClassFrame inner = CommandClassFrame.Create(CommandClassId.BinarySwitch, 0x01, [0x01, 0x02, 0x03]);
        Security0CommandClass.CommandEncapsulationCommand command =
            Security0CommandClass.CommandEncapsulationCommand.Create(sender, srcNodeId: 1, dstNodeId: 2, inner, 0x00);

        byte[] plaintext = new byte[1 + inner.Data.Length];
        plaintext[0] = 0x00;
        inner.Data.Span.CopyTo(plaintext.AsSpan(1));
        byte[] parameters = command.Frame.CommandParameters.Span.ToArray();
        byte[] ciphertext = parameters.AsSpan()[8..(8 + plaintext.Length)].ToArray();

        Assert.IsFalse(ciphertext.SequenceEqual(plaintext));
    }

